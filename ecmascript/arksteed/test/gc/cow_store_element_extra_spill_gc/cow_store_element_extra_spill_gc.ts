function storeWithLiveCowElements(array, obj) {
    // Copy-on-write store: the deferred block copies the elements and may trigger a GC.
    array[0] = 1;
    // holder[0] is a scanned heap slot, so a young GC updates it; obj only stays equal to it
    // when the extra spill slots are visited as GC roots.
    const same = obj === holder[0];
    return same && obj.text === "t";
}

